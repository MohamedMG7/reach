// Inlines xterm.js and its fit addon into assets/terminal.html and writes the result as a string
// module, so the terminal WebView needs no network and no bundled .html asset. Runs on npm install.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const read = (path) => readFileSync(require.resolve(path), 'utf8');
// A literal "</script" inside inlined code would end the <script> element early.
const script = (code) => code.replaceAll('</script', '<\\/script');

const page = readFileSync(new URL('../assets/terminal.html', import.meta.url), 'utf8')
  .replace('/*XTERM_CSS*/', () => read('@xterm/xterm/css/xterm.css'))
  .replace('/*XTERM_JS*/', () => script(read('@xterm/xterm/lib/xterm.js')))
  .replace('/*FIT_JS*/', () => script(read('@xterm/addon-fit/lib/addon-fit.js')));

const out = new URL('../src/terminal/terminalPage.generated.ts', import.meta.url);
mkdirSync(new URL('.', out), { recursive: true });
writeFileSync(
  out,
  `// Generated by scripts/build-terminal-page.mjs from assets/terminal.html. Do not edit.\nexport const terminalPage = ${JSON.stringify(page)};\n`,
);
